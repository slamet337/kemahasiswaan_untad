];

$rekap = [];
foreach ($kegiatan_rows as $row) {
  $kategori = $row->kategori;
  $juara = $peringkat_label[$row->peringkat] ?? 'LAINNYA';
  $total = $row->total;

  if (!isset($rekap[$kategori])) {
    $rekap[$kategori] = ['total' => 0, 'juara' => []];
  }

  $rekap[$kategori]['juara'][$juara] = $total;
  $rekap[$kategori]['total'] += $total;
}
?>

