      <h1 class="purecounter text-primary"
          data-purecounter-start="0"
          data-purecounter-end="<?= $data['total'] ?>"
          data-purecounter-duration="1"></h1>
      <h5 class="mb-4 text-uppercase">PRESTASI <?= strtoupper($kategori) ?></h5>

      <?php foreach ($data['juara'] as $label => $jumlah):
        $persen = ($data['total'] > 0) ? ($jumlah / $data['total']) * 100 : 0;
      ?>
        <div class="mb-2 position-relative" style="height: 100px;">
          <?php if ($persen >= 15): ?>
            <strong><?= strtoupper($label) ?></strong>
            <div class="progress" style="height: 80%;">
              <div class="progress-bar bg-warning d-flex justify-content-center align-items-center"
                   style="width: <?= $persen ?>%;">
                &nbsp;<h1><?= $jumlah ?> PRESTASI</h1>
              </div>
            </div>
          <?php else: ?>
            <div class="progress" style="height: 100%;">
              <div class="progress-bar bg-warning" style="width: <?= $persen ?>%;"></div>
            </div>
            <div class="position-absolute top-10 start-50 translate-middle text-white" style="z-index: 1;">
              <strong><?= strtoupper($label) ?>:</strong>&nbsp;<?= $jumlah ?> PRESTASI
